#!/usr/bin/env node
// Publishes a release folder (output of scripts/make-release.mjs) to dl.swordandseal.com through the Worker admin API
// (PUT/DELETE https://<host>/_admin/<key>, GET /_admin?prefix=). See docs/RELEASING.md.
//
//   DL_ADMIN_TOKEN=... node scripts/publish-release.mjs --dir release [--dry-run] [--keep N]
//   DL_ADMIN_TOKEN=... node scripts/publish-release.mjs --rollback <gameVersion> [--rollback-launcher <launcherVersion>]
//
// Options: --dir DIR (default release)  --host URL (default $DL_HOST or https://dl.swordandseal.com)  --concurrency N (6)
//          --retries N (4)  --dry-run  --keep N  --rollback V  --rollback-launcher V
// The token is read ONLY from the environment variable DL_ADMIN_TOKEN: never from arguments, never printed.
// Order: (1) versioned files, (2) stable-named launcher copies, (3) pointers LAST (feed ymls, game/latest/*, launcher/latest.json, news.json, releases.json).
// Phase 3 is skipped if any upload of phases 1-2 failed, so clients never see a pointer to missing files.
import fs from "node:fs";
import path from "node:path";
import { Readable } from "node:stream";
import { fileURLToPath } from "node:url";

const DEFAULT_HOST = "https://dl.swordandseal.com";
const STABLE = { win: "SwordAndSeal-Launcher-Setup.exe", mac: "SwordAndSeal-Launcher.dmg", linux: "SwordAndSeal-Launcher.AppImage" };
const TYPES = {
  json: "application/json", gz: "application/gzip", zip: "application/zip", exe: "application/vnd.microsoft.portable-executable",
  dmg: "application/x-apple-diskimage", appimage: "application/octet-stream", yml: "text/yaml", yaml: "text/yaml", txt: "text/plain", md: "text/plain",
  asc: "application/pgp-signature", blockmap: "application/octet-stream", js: "text/javascript", mjs: "text/javascript", cjs: "text/javascript",
  css: "text/css", html: "text/html", svg: "image/svg+xml", png: "image/png", jpg: "image/jpeg", jpeg: "image/jpeg", webp: "image/webp",
  ogg: "audio/ogg", mp3: "audio/mpeg", wav: "audio/wav", woff: "font/woff", woff2: "font/woff2", wasm: "application/wasm", map: "application/json",
};
function rangeTotal(res) {   // total object size from a 206 Content-Range (HEAD content-length is unreliable behind some proxies)
  const m = /\/(\d+)\s*$/.exec(res.headers.get("content-range") || "");
  return m ? Number(m[1]) : Number(res.headers.get("content-length"));
}
export function contentType(key) {
  const base = key.split("/").pop();
  if (base === "SHA256SUMS") return "text/plain";
  const ext = base.includes(".") ? base.split(".").pop().toLowerCase() : "";
  return TYPES[ext] || "application/octet-stream";
}
export const encodeKey = (k) => k.split("/").map(encodeURIComponent).join("/");
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const semverCmp = (a, b) => {
  const pa = String(a).split(/[-+]/)[0].split(".").map(Number), pb = String(b).split(/[-+]/)[0].split(".").map(Number);
  for (let i = 0; i < 3; i++) if ((pa[i] || 0) !== (pb[i] || 0)) return (pa[i] || 0) - (pb[i] || 0);
  return String(a).localeCompare(String(b));
};
const isVersion = (s) => /^\d+\.\d+\.\d+([-+][0-9A-Za-z.-]+)?$/.test(s);

/** Classify local files into publish phases. Keys are bucket keys (posix paths relative to the release dir). */
export function planUploads(dir) {
  const files = [];
  (function w(d) { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const a = path.join(d, e.name); if (e.isSymbolicLink()) continue; if (e.isDirectory()) w(a); else if (e.isFile()) files.push(a); } })(dir);
  const phases = { versioned: [], stable: [], pointers: [] };
  for (const abs of files.sort()) {
    const key = path.relative(dir, abs).split(path.sep).join("/");
    const item = { key, abs, size: fs.statSync(abs).size, type: contentType(key) };
    if (key === "releases.json") continue;   // generated by this script
    if (/^launcher\/latest\//.test(key)) phases.stable.push(item);
    else if (/^launcher\/feed\//.test(key) || /^game\/latest\//.test(key) || key === "launcher/latest.json" || key === "news.json") phases.pointers.push(item);
    else phases.versioned.push(item);
  }
  // pointer order: feed first, then game/latest/manifest.json, news, launcher/latest.json, root news.json
  const rank = (k) => (k.startsWith("launcher/feed/") ? 0 : k === "game/latest/manifest.json" ? 1 : k.startsWith("game/latest/") ? 2 : k === "launcher/latest.json" ? 3 : 4);
  phases.pointers.sort((a, b) => rank(a.key) - rank(b.key) || (a.key < b.key ? -1 : 1));
  return phases;
}
export function versionsIn(dir) {
  const ls = (p) => { try { return fs.readdirSync(path.join(dir, p), { withFileTypes: true }).filter((e) => e.isDirectory() && isVersion(e.name)).map((e) => e.name); } catch { return []; } };
  return { game: ls("game"), launcher: ls("launcher") };
}

export function makeClient({ host, token, retries = 4, log = () => {}, baseDelay = 400 }) {
  host = host.replace(/\/+$/, "");
  const auth = () => ({ authorization: `Bearer ${token}` });
  async function withRetry(label, fn) {
    let last;
    for (let i = 0; i <= retries; i++) {
      try { return await fn(); } catch (e) {
        last = e;
        if (e.fatal || i === retries) break;
        const wait = baseDelay * 2 ** i + Math.floor(Math.random() * 100);
        log(`  retry ${i + 1}/${retries} ${label}: ${e.message} (in ${wait} ms)`);
        await sleep(wait);
      }
    }
    throw new Error(`${label}: ${last.message}`);
  }
  const check = (res, what) => {
    if (res.status === 401 || res.status === 403) { const e = new Error(`${what} -> HTTP ${res.status} (bad or missing DL_ADMIN_TOKEN)`); e.fatal = true; throw e; }
    if (res.status === 400 || res.status === 413) { const e = new Error(`${what} -> HTTP ${res.status}`); e.fatal = true; throw e; }
    if (!res.ok) throw new Error(`${what} -> HTTP ${res.status}`);
  };
  const api = {
    host,
    async put(item) {
      if (!item.buffer && item.size > 64 * 1024 * 1024) return api.putMultipart(item);
      return withRetry(`PUT ${item.key}`, async () => {
        const headers = { ...auth(), "content-type": item.type, "content-length": String(item.size) };
        let body;
        if (item.buffer) body = item.buffer;
        else if (item.size <= 32 * 1024 * 1024) body = fs.readFileSync(item.abs);
        else body = Readable.toWeb(fs.createReadStream(item.abs));
        const res = await fetch(`${host}/_admin/${encodeKey(item.key)}`, { method: "PUT", headers, body, duplex: "half" });
        check(res, `PUT ${item.key}`);
        await res.arrayBuffer().catch(() => {});
      });
    },
    async putMultipart(item) {   // objects above the Worker body limit: 32 MB parts, each retried
      const base = `${host}/_admin/${encodeKey(item.key)}`;
      const created = await withRetry(`MPU create ${item.key}`, async () => {
        const res = await fetch(`${base}?mpu=create`, { method: "POST", headers: { ...auth(), "content-type": item.type } });
        check(res, `MPU create ${item.key}`); return res.json();
      });
      const PART = 32 * 1024 * 1024, parts = [], fd = fs.openSync(item.abs, "r");
      try {
        for (let off = 0, n = 1; off < item.size; off += PART, n++) {
          const len = Math.min(PART, item.size - off), buf = Buffer.alloc(len);
          fs.readSync(fd, buf, 0, len, off);
          parts.push(await withRetry(`MPU part ${n} ${item.key}`, async () => {
            const res = await fetch(`${base}?mpu=part&id=${encodeURIComponent(created.id)}&n=${n}`, { method: "PUT", headers: auth(), body: buf });
            check(res, `MPU part ${n} ${item.key}`); return res.json();
          }));
        }
      } finally { fs.closeSync(fd); }
      await withRetry(`MPU complete ${item.key}`, async () => {
        const res = await fetch(`${base}?mpu=complete&id=${encodeURIComponent(created.id)}`, { method: "POST", headers: { ...auth(), "content-type": "application/json" }, body: JSON.stringify(parts) });
        check(res, `MPU complete ${item.key}`); await res.arrayBuffer().catch(() => {});
      });
    },
    async verify(item) {   // HEAD on the public URL (cache-busted); size must match
      return withRetry(`HEAD ${item.key}`, async () => {
        const res = await fetch(`${host}/${encodeKey(item.key)}?_=${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`, { headers: { range: "bytes=0-0" } });
        if (res.status === 404) throw new Error(`HEAD ${item.key} -> 404 after upload`);
        if (!res.ok) throw new Error(`HEAD ${item.key} -> HTTP ${res.status}`);
        await res.arrayBuffer().catch(() => {});
        const len = rangeTotal(res);
        if (len !== item.size) throw new Error(`HEAD ${item.key}: size ${len} != expected ${item.size}`);
      });
    },
    async del(key) {
      return withRetry(`DELETE ${key}`, async () => { const res = await fetch(`${host}/_admin/${encodeKey(key)}`, { method: "DELETE", headers: auth() }); check(res, `DELETE ${key}`); await res.arrayBuffer().catch(() => {}); });
    },
    async list(prefix) {
      return withRetry(`LIST ${prefix}`, async () => {
        const res = await fetch(`${host}/_admin?prefix=${encodeURIComponent(prefix)}`, { headers: auth() });
        check(res, `LIST ${prefix}`);
        const j = await res.json();
        return Array.isArray(j) ? j : j.objects || [];
      });
    },
    async getPublic(key, { optional = false } = {}) {   // returns Buffer, or null for 404 when optional
      return withRetry(`GET ${key}`, async () => {
        const res = await fetch(`${host}/${encodeKey(key)}?_=${Date.now().toString(36)}${Math.random().toString(36).slice(2, 6)}`);
        if (res.status === 404 && optional) return null;
        if (!res.ok) throw new Error(`GET ${key} -> HTTP ${res.status}`);
        return Buffer.from(await res.arrayBuffer());
      });
    },
    async headSize(key) {
      const res = await fetch(`${host}/${encodeKey(key)}?_=${Date.now().toString(36)}`, { headers: { range: "bytes=0-0" } });
      await res.arrayBuffer().catch(() => {});
      return res.ok ? rangeTotal(res) : null;
    },
  };
  return api;
}

async function pool(items, n, fn) {
  const results = new Array(items.length);
  let i = 0, failed = 0;
  await Promise.all(Array.from({ length: Math.max(1, Math.min(n, items.length)) }, async () => {
    while (i < items.length) {
      const idx = i++;
      try { results[idx] = { ok: true, value: await fn(items[idx], idx) }; } catch (e) { failed++; results[idx] = { ok: false, error: e }; }
    }
  }));
  return { results, failed };
}

const fmtMB = (n) => (n / 1048576).toFixed(1) + " MB";

async function uploadPhase(api, name, items, { concurrency, log }) {
  if (!items.length) return 0;
  log(`${name}: ${items.length} file(s), ${fmtMB(items.reduce((s, x) => s + x.size, 0))}`);
  let done = 0;
  const { results, failed } = await pool(items, concurrency, async (item) => {
    await api.put(item);
    await api.verify(item);
    done++;
    if (items.length <= 40 || done % 25 === 0 || done === items.length) log(`  [${done}/${items.length}] ${item.key} (${fmtMB(item.size)}) ok`);
  });
  for (const r of results) if (!r.ok) log(`  FAILED ${r.error.message}`);
  return failed;
}

async function putJson(api, key, obj, log) {
  const buffer = Buffer.from(JSON.stringify(obj, null, 2) + "\n");
  const item = { key, buffer, size: buffer.length, type: "application/json" };
  await api.put(item); await api.verify(item);
  log(`  ${key} ok`);
}

async function readIndex(api) {
  const buf = await api.getPublic("releases.json", { optional: true });
  try { const j = JSON.parse(buf.toString("utf8")); return { game: j.game || [], launcher: j.launcher || [] }; } catch { return { game: [], launcher: [] }; }
}

async function deletePrefix(api, prefix, log) {
  let total = 0;
  for (let round = 0; round < 200; round++) {   // list is capped at 1000 objects by the Worker: repeat until empty
    const objs = await api.list(prefix);
    if (!objs.length) break;
    const { failed } = await pool(objs, 8, (o) => api.del(o.key));
    total += objs.length - failed;
    if (failed) throw new Error(`failed to delete ${failed} object(s) under ${prefix}`);
  }
  log(`  deleted ${total} object(s) under ${prefix}`);
}

async function main() {
  const argv = process.argv.slice(2);
  const flag = (n) => argv.includes(`--${n}`);
  const opt = (n, d) => { const i = argv.indexOf(`--${n}`); return i >= 0 && argv[i + 1] && !argv[i + 1].startsWith("--") ? argv[i + 1] : d; };
  if (flag("help") || flag("h")) { console.log(fs.readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").slice(1, 12).map((l) => l.replace(/^\/\/ ?/, "")).join("\n")); return 0; }
  if (argv.some((a) => /^--(token|admin-token|dl-admin-token)/.test(a))) { console.error("The token must be passed in the DL_ADMIN_TOKEN environment variable, not as an argument."); return 2; }
  const log = (m) => console.log(m);
  const dry = flag("dry-run");
  const host = opt("host", process.env.DL_HOST || DEFAULT_HOST);
  if (!/^https?:\/\//.test(host)) { console.error("--host must be an http(s) URL"); return 2; }
  const token = process.env.DL_ADMIN_TOKEN || "";
  const concurrency = Number(opt("concurrency", "6")) || 6;
  const retries = Number(opt("retries", "4"));
  const keepArg = opt("keep");
  const keep = keepArg === undefined ? null : Number(keepArg);
  if (keep !== null && (!Number.isInteger(keep) || keep < 1)) { console.error("--keep needs an integer >= 1"); return 2; }
  const rbGame = opt("rollback"), rbLauncher = opt("rollback-launcher");
  if (flag("rollback") && !rbGame) { console.error("--rollback needs a game version"); return 2; }
  if (flag("rollback-launcher") && !rbLauncher) { console.error("--rollback-launcher needs a launcher version"); return 2; }
  if (!dry && !token) { console.error("DL_ADMIN_TOKEN is not set (environment variable). Use --dry-run to only print the plan."); return 2; }
  const api = makeClient({ host, token, retries, log });

  // ---- rollback ----
  if (rbGame || rbLauncher) {
    log(`${dry ? "[dry-run] " : ""}Rollback on ${host}`);
    const writes = [];
    if (rbGame) {
      if (!isVersion(rbGame)) { console.error(`Bad version ${rbGame}`); return 2; }
      const mbuf = await api.getPublic(`game/${rbGame}/manifest.json`, { optional: true });
      if (!mbuf) { console.error(`game/${rbGame}/manifest.json does not exist (pruned?). Cannot roll back.`); return 1; }
      const manifest = JSON.parse(mbuf.toString("utf8"));
      const missing = [];
      await pool(manifest.files || [], concurrency, async (f) => {
        const k = `game/${rbGame}/files/${f.path}${f.gz ? ".gz" : ""}`;
        const sz = await api.headSize(k);
        if (sz === null) missing.push(k);
      });
      if (missing.length) { console.error(`${missing.length} file(s) of ${rbGame} are missing (e.g. ${missing[0]}). Refusing to roll back.`); return 1; }
      const news = await api.getPublic(`game/${rbGame}/news.json`, { optional: true });
      writes.push({ key: "game/latest/manifest.json", json: { ...manifest, filesBase: `../${rbGame}/files/` } });
      if (news) { writes.push({ key: "game/latest/news.json", buffer: news }); writes.push({ key: "news.json", buffer: news }); }
    }
    if (rbLauncher) {
      const rbuf = await api.getPublic(`launcher/${rbLauncher}/release.json`, { optional: true });
      if (!rbuf) { console.error(`launcher/${rbLauncher}/release.json does not exist. Cannot roll back the launcher.`); return 1; }
      const rel = JSON.parse(rbuf.toString("utf8"));
      for (const [p, fixed] of Object.entries(STABLE)) {
        const f = rel.files?.[p]; if (!f) continue;
        const name = f.name || decodeURIComponent(String(f.url).split("/").pop());
        const bytes = await api.getPublic(`launcher/${rbLauncher}/${name}`);
        writes.push({ key: `launcher/latest/${fixed}`, buffer: bytes, type: contentType(fixed) });
        rel.stable = { ...(rel.stable || {}), [p]: `${host}/launcher/latest/${fixed}` };
      }
      for (const yml of ["latest.yml", "latest-mac.yml", "latest-linux.yml"]) {
        const y = await api.getPublic(`launcher/${rbLauncher}/${yml}`, { optional: true });
        if (y) writes.push({ key: `launcher/feed/${yml}`, buffer: Buffer.from(y.toString("utf8").replace(/^(\s*(?:-\s+)?(?:url|path):\s*)(?!https?:|\.\.\/)(\S.*)$/gm, (_m, a, b) => `${a}../${rbLauncher}/${b.trim()}`)), type: "text/yaml" });
      }
      writes.push({ key: "launcher/latest.json", json: rel });   // pointer last
    }
    // order: stable copies and feed first, JSON pointers last
    writes.sort((a, b) => (a.json ? 1 : 0) - (b.json ? 1 : 0));
    for (const w of writes) {
      const buffer = w.buffer || Buffer.from(JSON.stringify(w.json, null, 2) + "\n");
      if (dry) { log(`  would PUT ${w.key} (${buffer.length} bytes)`); continue; }
      const item = { key: w.key, buffer, size: buffer.length, type: w.type || "application/json" };
      await api.put(item); await api.verify(item); log(`  ${w.key} ok`);
    }
    log(dry ? "Dry run: nothing written." : "Rollback done.");
    return 0;
  }

  // ---- publish ----
  const dir = path.resolve(opt("dir", "release"));
  if (!fs.existsSync(dir)) { console.error(`Release directory ${dir} not found. Run: node scripts/make-release.mjs`); return 2; }
  const plan = planUploads(dir);
  const all = [...plan.versioned, ...plan.stable, ...plan.pointers];
  if (!plan.pointers.some((p) => p.key === "game/latest/manifest.json") && !plan.pointers.some((p) => p.key === "launcher/latest.json")) { console.error("No pointer files (game/latest/manifest.json or launcher/latest.json) in the release dir; is it the make-release output?"); return 2; }
  log(`${dry ? "[dry-run] " : ""}Publishing ${path.relative(process.cwd(), dir) || "."} to ${host}: ${all.length} files, ${fmtMB(all.reduce((s, x) => s + x.size, 0))}`);
  if (dry) {
    for (const [name, items] of Object.entries(plan)) {
      log(`${name} (${items.length})`);
      for (const it of items.slice(0, name === "versioned" ? 12 : 100)) log(`  ${it.key}  ${it.size} B  ${it.type}`);
      if (items.length > 12 && name === "versioned") log(`  ... ${items.length - 12} more`);
    }
    log(`releases.json  <- game ${JSON.stringify(versionsIn(dir).game)} launcher ${JSON.stringify(versionsIn(dir).launcher)}`);
    if (keep) log(`--keep ${keep}: would prune older versions after publishing (decided against releases.json at publish time)`);
    log("Dry run: nothing written.");
    return 0;
  }
  let failed = await uploadPhase(api, "1/3 versioned files", plan.versioned, { concurrency, log });
  failed += await uploadPhase(api, "2/3 stable-named launcher copies", plan.stable, { concurrency, log });
  if (failed) { console.error(`${failed} upload(s) failed. Pointers (latest) were NOT updated; the previous release is still live. Re-run to retry.`); return 1; }
  log(`3/3 pointers (last): ${plan.pointers.length} file(s)`);
  for (const item of plan.pointers) { await api.put(item); await api.verify(item); log(`  ${item.key} ok`); }
  const index = await readIndex(api);
  const local = versionsIn(dir);
  const merged = { game: [...new Set([...index.game, ...local.game])].sort(semverCmp), launcher: [...new Set([...index.launcher, ...local.launcher])].sort(semverCmp) };
  if (keep) {
    const livePointer = async (key, field) => { try { return JSON.parse((await api.getPublic(key)).toString("utf8"))[field]; } catch { return null; } };
    const curGame = await livePointer("game/latest/manifest.json", "version"), curLauncher = await livePointer("launcher/latest.json", "version");
    for (const [kind, list, cur] of [["game", merged.game, curGame], ["launcher", merged.launcher, curLauncher]]) {
      const keepSet = new Set(list.slice(-keep)); if (cur) keepSet.add(cur);
      const drop = list.filter((v) => !keepSet.has(v));
      for (const v of drop) { log(`prune ${kind} ${v}`); await deletePrefix(api, `${kind}/${v}/`, log); }
      merged[kind] = list.filter((v) => keepSet.has(v));
    }
  }
  await putJson(api, "releases.json", { ...merged, updatedAt: new Date().toISOString() }, log);
  log("Published.");
  return 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().then((c) => process.exit(c), (e) => { console.error(String(e?.message || e).replace(/Bearer\s+\S+/g, "Bearer ***")); process.exit(1); });
}
